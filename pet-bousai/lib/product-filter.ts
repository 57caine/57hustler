/**
 * 楽天市場の商品名の扱い（取得スクリプトとテストで共用）。
 *
 * 除外する商品（商品名のどこかに含まれていれば除外）:
 * - 医薬品・医療機器と誤認されうる表現: 効く・防ぐ・予防・改善・治療・薬・殺菌 など
 * - 根拠を当サイトで確認できない順位・推奨・監修の表現: 1位・ランキング・No.1・推奨・監修 など
 * - 断定・あおり表現: 絶対・必須・最強・安心・安全 など（安全性を当サイトが保証していると読まれないようにする）
 * - 価格・割引・期間限定の表記（当サイトは価格を表示しない方針のため、商品名経由で古い価格が残らないようにする）
 */

/** 商品名全体（括弧書きを含む）で判定する: 誤認・順位・推奨・あおり表現 */
const NG_ANYWHERE =
  /効く|効果|効能|防ぐ|防止|予防|改善|治療|治る|薬|医療|医薬|殺菌|除菌|抗菌|ウイルス|1位|１位|一位|ランキング|ランク|No\.?\s*1|ナンバーワン|受賞|推奨|監修|獣医|絶対|必須|最強|安心|安全|人気|話題|おすすめ|オススメ/i;

/** 表示する商品名（括弧書きを除いた部分）で判定する: 価格・割引・期間限定の表記 */
const NG_DISPLAYED = /最安|激安|当選|クーポン|OFF|オフ|割引|％|%|￥|¥|\d+円|ポイント|P\d+倍|SALE|セール|まで|迄|限定|送料無料/i;

export function isExcludedName(name: string): boolean {
  return NG_ANYWHERE.test(name) || NG_DISPLAYED.test(displayName(name));
}

/** 表示用の商品名: 【】［］などの括弧書き（ショップの宣伝文）を除き、空白を整える */
export function displayName(name: string): string {
  const cleaned = name
    .replace(/【[^】]*】|［[^］]*］|\[[^\]]*\]|＼[^／]*／|★[^★]*★|《[^》]*》|≪[^≫]*≫/g, ' ')
    .replace(/[\s　]+/g, ' ')
    .trim();
  return cleaned.length > 0 ? cleaned : name.trim();
}
