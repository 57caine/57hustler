import { PROTOCOL_VERSION, TOOLS, parseRpc,parseArgs,rpcOk,rpcError,validKey,validUuid,sameIdempotentRequest,parseToolCallParams } from './mcp-contract';
function expect(condition:boolean,detail:string){if(!condition)throw new Error(detail);}
export function testMcpContract(){
  expect(PROTOCOL_VERSION==='2025-11-25','protocol version');
  expect(TOOLS.length===4,'four supported tools');
  expect(new Set(TOOLS.map(t=>t.name)).size===4,'unique tool names');
  expect(TOOLS.every(t=>t.inputSchema.additionalProperties===false),'closed schemas');
  expect(parseRpc({jsonrpc:'2.0',id:1,method:'initialize'})?.method==='initialize','initialize');
  expect(parseRpc({jsonrpc:'2.0',id:2,method:'tools/list'})?.id===2,'tools list');
  expect(parseRpc({jsonrpc:'2.0',method:'notifications/initialized'})?.id===undefined,'notification');
  expect(parseRpc({jsonrpc:'1.0',id:1,method:'initialize'})===null,'invalid version');
  expect(parseRpc([{jsonrpc:'2.0',id:1,method:'ping'}])===null,'batch unsupported');
  expect(parseRpc({jsonrpc:'2.0',id:1.5,method:'ping'})===null,'fractional id rejected');
  expect(parseRpc({jsonrpc:'2.0',id:Infinity,method:'ping'})===null,'infinite id rejected');
  expect(parseRpc({jsonrpc:'2.0',id:NaN,method:'ping'})===null,'NaN id rejected');
  expect(parseRpc({jsonrpc:'2.0',id:9007199254740992,method:'ping'})===null,'unsafe integer id rejected');
  expect(parseRpc({jsonrpc:'2.0',id:1,method:''})===null,'empty method rejected');
  expect(parseArgs({requestId:'123'},['requestId'])?.requestId==='123','read args');
  expect(parseArgs({requestId:'123',owner_id:'other'},['requestId'])===null,'no IDOR argument');
  expect(parseArgs({requestId:123},['requestId'])===null,'typed arguments');
  expect(validKey('01234567'),'valid idempotency');
  expect(!validKey('a b c d e'),'invalid idempotency');
  expect(validUuid('123e4567-e89b-42d3-a456-426614174000'),'valid UUID');
  expect(!validUuid('not-a-uuid'),'invalid UUID');
  expect(rpcOk(1,{ok:true}).jsonrpc==='2.0','rpc success shape');
  expect(rpcError(null,-32700,'parse error').error.code===-32700,'rpc failure shape');
  expect(sameIdempotentRequest({question:'hello',origin:'chatgpt'},{question:' hello ',origin:'chatgpt'}),'same replay accepted after trim');
  expect(!sameIdempotentRequest({question:'hello',origin:'chatgpt'},{question:'different',origin:'chatgpt'}),'changed question rejected');
  expect(!sameIdempotentRequest({question:'hello',origin:'chatgpt'},{question:'hello',origin:'claude'}),'changed origin rejected');
  expect(parseRpc({jsonrpc:'2.0',id:null,method:'ping'})===null,'null JSON-RPC id rejected');
  expect(parseRpc({jsonrpc:'2.0',id:{value:1},method:'ping'})===null,'object JSON-RPC id rejected');
  expect(parseRpc({jsonrpc:'2.0',id:'x'.repeat(101),method:'ping'})===null,'oversized JSON-RPC id rejected');
  expect(parseRpc({jsonrpc:'2.0',id:1,method:'x'.repeat(101)})===null,'oversized method rejected');
  expect(parseArgs({requestId:'123',__proto__:null},['requestId'])?.requestId==='123','ordinary arguments accepted');
  expect(parseArgs({requestId:'123',extra:'unsafe'},['requestId'])===null,'unexpected argument rejected');
  expect(parseArgs({},['requestId'])===null,'missing required argument rejected');
  expect(!validKey('a'.repeat(129)),'oversized idempotency key rejected');
  expect(!validKey('abc\\n12345678'),'control character in key rejected');
  expect(!sameIdempotentRequest({question:'hello',origin:'chatgpt'},{question:'hello',origin:'gemini'}),'cross-provider replay rejected');
  expect(parseArgs(Object.create({requestId:'inherited'}),['requestId'])===null,'inherited required property rejected');
  expect(parseArgs({requestId:'own'},['requestId'])?.requestId==='own','own required property accepted');
  expect(parseToolCallParams({name:'get_status',arguments:{requestId:'123'}})?.name==='get_status','valid tool envelope');
  expect(parseToolCallParams({name:'get_status',arguments:{},owner_id:'other'})===null,'extra envelope key rejected');
  expect(parseToolCallParams(Object.create({name:'get_status',arguments:{}}))===null,'inherited tool name rejected');
  expect(parseToolCallParams({name:'get_status'})===null,'missing arguments rejected');
  expect(parseToolCallParams({name:'get_status',arguments:[]})===null,'array arguments rejected');
  expect(parseToolCallParams({name:'',arguments:{}})===null,'empty tool name rejected');
  expect(parseToolCallParams({name:'x'.repeat(101),arguments:{}})===null,'oversized tool name rejected');
  return 'mcp contract 45 checks passed';
}
